#!/usr/bin/env python3
"""Generate C++ tables from the original C# sources (HtmlTag, HtmlAttribute, HtmlEntities).

Usage: python3 -I tools/gen_tables.py [path-to-csharp-src]

Reads:
  <src>/z3l.FastHtmlParser/HtmlTag.cs
  <src>/z3l.FastHtmlParser/HtmlAttribute.cs
  <src>/z3l.FastHtmlParser/Core/HtmlNames.cs
  <src>/z3l.FastHtmlParser/Core/HtmlEntities.Table.cs

Writes:
  include/fh/generated_names.hpp
  src/generated_entities.cpp
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SRC = ROOT / "ref" / "csharp" / "src"


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def enum_members(path: Path, enum_name: str) -> list[str]:
    text = path.read_text(encoding="utf-8")
    m = re.search(r"public enum %s\s*\{(.*?)\n\}" % enum_name, text, re.S)
    if not m:
        raise SystemExit(f"enum {enum_name} not found in {path}")
    body = strip_comments(m.group(1))
    members = []
    for line in body.splitlines():
        line = line.strip()
        if not line:
            continue
        m2 = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*,?$", line)
        if m2:
            members.append(m2.group(1))
    return members


def special_names(path: Path, enum_name: str) -> dict[str, str]:
    """The `Special` switch: Member => "name"."""
    text = path.read_text(encoding="utf-8")
    m = re.search(r"private static string\? Special\(%s[^)]*\) => [^;]*?;\n" % enum_name, text, re.S)
    if not m:
        return {}
    result = {}
    for member, value in re.findall(r"%s\.([A-Za-z0-9_]+)\s*=>\s*\"([^\"]*)\"" % enum_name, m.group(0)):
        result[member] = value
    return result


def cstring(value: str) -> str:
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            for byte in ch.encode("utf-8"):
                out.append("\\x%02x" % byte)
            out.append('""')  # break the hex escape so the next char is not swallowed
    return "".join(out)


def parse_cs_strings(path: Path, field: str) -> str:
    """Concatenated C# string literal of a `private const string <field> = ...;` declaration."""
    text = path.read_text(encoding="utf-8")
    m = re.search(r"private const string %s\s*=\s*(.*?);" % field, text, re.S)
    if not m:
        raise SystemExit(f"{field} not found in {path}")
    literals = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
    raw = "".join(literals)
    # C# and Python escapes agree for \uXXXX, \0, \", \\ (no \x in this file).
    return raw.encode("utf-8").decode("unicode_escape")


def utf16_to_utf8(units: list[int]) -> str:
    out = []
    i = 0
    while i < len(units):
        u = units[i]
        if 0xD800 <= u <= 0xDBFF and i + 1 < len(units) and 0xDC00 <= units[i + 1] <= 0xDFFF:
            cp = 0x10000 + ((u - 0xD800) << 10) + (units[i + 1] - 0xDC00)
            i += 2
        else:
            cp = u
            i += 1
        out.append(chr(cp))
    return "".join(out)


def main() -> int:
    src = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else DEFAULT_SRC
    base = src / "z3l.FastHtmlParser"

    tag_members = enum_members(base / "HtmlTag.cs", "HtmlTag")
    attr_members = enum_members(base / "HtmlAttribute.cs", "HtmlAttribute")
    tag_special = special_names(base / "Core" / "HtmlNames.cs", "HtmlTag")
    attr_special = special_names(base / "Core" / "HtmlNames.cs", "HtmlAttribute")

    def lower(member: str) -> str:
        return member.lower()

    tag_names = [tag_special.get(m, lower(m)) for m in tag_members]
    attr_names = [attr_special.get(m, lower(m)) for m in attr_members]

    # --- names header -------------------------------------------------------
    lines = [
        "// Generated by tools/gen_tables.py from the C# sources. Do not edit.",
        "#pragma once",
        "",
        "#include <string_view>",
        "",
        "namespace fh {",
        "",
        "// Known tag names (HtmlTag in the original).",
        "enum class HtmlTag : int {",
    ]
    for m in tag_members:
        lines.append(f"    {m},")
    lines += [
        "};",
        f"inline constexpr int kTagCount = {len(tag_members)};",
        "",
        "// Known attribute names (HtmlAttribute in the original).",
        "enum class Attr : int {",
    ]
    for m in attr_members:
        lines.append(f"    {m},")
    lines += [
        "};",
        f"inline constexpr int kAttrCount = {len(attr_members)};",
        "",
        "inline constexpr std::string_view kTagNames[] = {",
    ]
    for name in tag_names:
        lines.append(f'    "{cstring(name)}",')
    lines += ["};", "", "inline constexpr std::string_view kAttrNames[] = {"]
    for name in attr_names:
        lines.append(f'    "{cstring(name)}",')
    lines += ["};", "", "}  // namespace fh", ""]

    out_names = ROOT / "include" / "fh" / "generated_names.hpp"
    out_names.parent.mkdir(parents=True, exist_ok=True)
    out_names.write_text("\n".join(lines), encoding="utf-8")

    # --- entities -----------------------------------------------------------
    table = base / "Core" / "HtmlEntities.Table.cs"
    names_raw = parse_cs_strings(table, "Names")
    values_raw = parse_cs_strings(table, "Values")

    names = [n for n in names_raw.split(" ") if n]
    # Values: pairs of UTF-16 code units, the second one may be '\0'.
    if len(values_raw) % 2:
        raise SystemExit("Values length is odd")
    units = [ord(ch) for ch in values_raw]
    entries = []
    for i, raw_name in enumerate(names):
        legacy = raw_name.startswith("+")
        name = raw_name[1:] if legacy else raw_name
        pair = units[2 * i : 2 * i + 2]
        if pair[1] == 0:
            pair = pair[:1]
        entries.append((name, utf16_to_utf8(pair), legacy))

    entries.sort(key=lambda e: e[0])
    if len({e[0] for e in entries}) != len(entries):
        raise SystemExit("duplicate entity names")

    max_name = max(len(e[0]) for e in entries)
    max_legacy = max(len(e[0]) for e in entries if e[2])

    lines = [
        "// Generated by tools/gen_tables.py from HtmlEntities.Table.cs. Do not edit.",
        '#include "fh/generated_entities.hpp"',
        "",
        "namespace fh::detail {",
        "",
        "const EntityEntry kEntities[] = {",
    ]
    for name, value, legacy in entries:
        lines.append(f'    {{"{cstring(name)}", "{cstring(value)}", {"true" if legacy else "false"}}},')
    lines += [
        "};",
        f"const std::size_t kEntityCount = {len(entries)};",
        f"const std::size_t kMaxEntityNameLength = {max_name};",
        f"const std::size_t kMaxLegacyEntityNameLength = {max_legacy};",
        "",
        "}  // namespace fh::detail",
        "",
    ]
    (ROOT / "src").mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "generated_entities.cpp").write_text("\n".join(lines), encoding="utf-8")

    # --- entities header ----------------------------------------------------
    header = """// Generated by tools/gen_tables.py. Do not edit.
#pragma once

#include <cstddef>
#include <cstdint>
#include <string_view>

namespace fh::detail {

struct EntityEntry {
    std::string_view name;
    std::string_view value;
    bool legacy;
};

extern const EntityEntry kEntities[];
extern const std::size_t kEntityCount;
extern const std::size_t kMaxEntityNameLength;
extern const std::size_t kMaxLegacyEntityNameLength;

// Case-sensitive lookup of an entity name (without '&' and ';').
const EntityEntry* find_entity(std::string_view name);

}  // namespace fh::detail
"""
    (ROOT / "include" / "fh").mkdir(parents=True, exist_ok=True)
    (ROOT / "include" / "fh" / "generated_entities.hpp").write_text(header, encoding="utf-8")

    print(f"tags: {len(tag_members)}, attributes: {len(attr_members)}, entities: {len(entries)}")
    print(f"max entity name: {max_name}, max legacy name: {max_legacy}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
